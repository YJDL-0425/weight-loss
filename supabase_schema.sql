-- ============================================
-- 减肥数据看板 - Supabase 建表脚本（多用户隔离版 v2）
-- 用法：Supabase → SQL Editor → 粘贴全部 → Run
-- 注意：v2 会先删除旧表再重建（仅当表里没有重要数据时执行！），
--       v1 旧数据会清空。所有数据按 user_code 隔离。
-- ============================================

-- 清理旧表（含旧策略）
drop table if exists daily_logs;
drop table if exists food_entries;
drop table if exists exercise_entries;
drop table if exists settings;
drop policy if exists public_photos_all on storage.objects;

-- 1. 每日基础数据（体重/睡眠/心情/备注）
create table daily_logs (
  id bigint generated by default as identity primary key,
  user_code text not null default 'default',
  date date not null,
  weight real,
  sleep_hours real,
  mood integer,
  note text,
  created_at timestamptz default now(),
  unique (user_code, date)
);

-- 2. 食物明细（每天多条）
create table food_entries (
  id bigint generated by default as identity primary key,
  user_code text not null default 'default',
  date date not null,
  name text,
  amount real,
  unit text,
  calories real,
  created_at timestamptz default now()
);

-- 3. 运动明细（每天多条）
create table exercise_entries (
  id bigint generated by default as identity primary key,
  user_code text not null default 'default',
  date date not null,
  name text,
  minutes real,
  calories real,
  created_at timestamptz default now()
);

-- 4. 设置（key-value，按用户隔离）
create table settings (
  user_code text not null default 'default',
  key text not null,
  value text,
  primary key (user_code, key)
);

-- ============================================
-- 开启行级安全（RLS），并允许匿名客户端访问
-- MVP 阶段：应用层按 user_code 隔离。以后加登录后再收紧 RLS。
-- ============================================
alter table daily_logs enable row level security;
alter table food_entries enable row level security;
alter table exercise_entries enable row level security;
alter table settings enable row level security;

create policy "anon_all_daily_logs" on daily_logs
  for all to anon using (true) with check (true);
create policy "anon_all_food_entries" on food_entries
  for all to anon using (true) with check (true);
create policy "anon_all_exercise_entries" on exercise_entries
  for all to anon using (true) with check (true);
create policy "anon_all_settings" on settings
  for all to anon using (true) with check (true);

-- ============================================
-- 照片存储桶（公开，按 user_code/日期.jpg 分文件夹隔离）
-- ============================================
insert into storage.buckets (id, name, public)
values ('photos', 'photos', true)
on conflict (id) do nothing;

create policy "public_photos_all" on storage.objects
  for all to anon
  using (bucket_id = 'photos')
  with check (bucket_id = 'photos');
